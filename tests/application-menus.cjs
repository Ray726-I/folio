const assert = require('node:assert/strict');
const { openEditor } = require('./editor-browser.cjs');
(async () => {
  const source = '# Report\n\nOriginal **text**.\n\n## Next section\n';
  const session = await openEditor(source, undefined, { reading: true });
  try {
    const { page } = session;
    assert.equal(await page.locator('#app-menubar').count(), 1, 'application menus have their own level');
    assert.equal(await page.locator('#document-mode-label').textContent(), 'Read');
    assert.equal(await page.locator('#preview .ProseMirror').getAttribute('contenteditable'), 'false');
    assert.equal(await page.locator('.folio-heading-source').isVisible(), false, 'Reading displays rendered headings');
    await page.locator('#document-mode-button').click();
    assert.equal(await page.locator('#document-mode-label').textContent(), 'Edit', 'the main mode button toggles Read → Edit');
    assert.equal(await page.locator('#document-mode-menu').isVisible(), false, 'the main mode button does not open the menu');
    await page.locator('#document-mode-button').click();
    assert.equal(await page.locator('#document-mode-label').textContent(), 'Read', 'the main mode button toggles Edit → Read without stopping at Source');
    await page.locator('#document-mode-menu-button').click();
    assert.deepEqual(await page.locator('#document-mode-menu [data-document-mode]').allTextContents(), ['Read', 'Edit', 'Source'], 'mode labels drop the repeated word');
    const original = await page.evaluate(() => current.content);
    await page.getByRole('menuitemradio', { name: 'Source', exact: true }).click();
    await page.locator('#document-source').fill(original + '\nSource addition.\n');
    await page.locator('#document-mode-menu-button').click();
    await page.getByRole('menuitemradio', { name: 'Edit', exact: true }).click();
    assert.equal(await page.locator('#preview .ProseMirror').getAttribute('contenteditable'), 'true');
    assert.match(await page.evaluate(() => current.content), /Source addition/);
    await page.keyboard.press('Control+z');
    assert.equal(await page.evaluate(() => current.content), original, 'source and rich edits share undo');
    await page.locator('#document-mode-menu-button').click();
    await page.getByRole('menuitemcheckbox', { name: 'Open as read-only', exact: true }).click();
    assert.equal(await page.locator('#preview .ProseMirror').getAttribute('contenteditable'), 'false');
    await page.evaluate(() => { current.writable = false; syncDocumentMode(); });
    await page.locator('#document-mode-menu-button').click();
    assert.equal(await page.getByRole('menuitemradio', { name: 'Edit', exact: true }).isDisabled(), true);
    assert.match(await page.locator('#filesystem-permission').textContent(), /permissions/i);
    await page.keyboard.press('Escape');
    await page.evaluate(() => { current.writable = true; documentReadOnly = false; setDocumentMode('edit'); });
    await page.keyboard.press('Control+h');
    await page.locator('#find-input').fill('Original');
    await page.locator('#replace-input').fill('Replaced');
    await page.locator('#replace-all').click();
    assert.match(await page.evaluate(() => current.content), /Replaced \*\*text\*\*/);
    await page.locator('#find-close').click();
    await page.locator('#view-menu-button').click();
    await page.locator('#preference-line-height').evaluate(input => { input.value = '1.9'; });
    await page.locator('#preference-line-height').dispatchEvent('input');
    assert.equal(await page.evaluate(() => localStorage.getItem('folio.lineHeight')), '1.9');
    await page.keyboard.press('Escape');
    await page.locator('#menu-file-button').focus();
    await page.keyboard.press('ArrowDown');
    assert.equal(await page.locator('#open-menu').isVisible(), true);
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#edit-menu').isVisible(), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'menu-edit-button');
    await page.locator('#document-more-button').click();
    await page.getByRole('menuitem', { name: 'Duplicate…', exact: true }).click();
    await page.waitForFunction(() => calls.some(call => call.command === 'duplicate_document'));
    // A delayed clipboard read must never edit the next document.
    await page.evaluate(() => {
      setDocumentMode('source');
      Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { readText: () => new Promise(resolve => { window.releaseClipboard = resolve; }) } });
      void editClipboard('paste');
    });
    await page.evaluate(() => openPath('/tmp/other.md', true));
    await page.evaluate(() => { setDocumentMode('source'); window.releaseClipboard('STALE PASTE'); });
    assert.equal(await page.evaluate(() => current.content), source);
    // Preference controls keep their native keyboard behavior inside the panel.
    await page.locator('#view-menu-button').click();
    await page.locator('#preference-line-height').focus();
    const beforeHeight = await page.locator('#preference-line-height').inputValue();
    await page.keyboard.press('ArrowRight');
    assert.notEqual(await page.locator('#preference-line-height').inputValue(), beforeHeight);
    await page.keyboard.press('Escape');
    await page.evaluate(() => { runAppAction('bottom'); });
    await page.evaluate(() => { runAppAction('top'); });
    assert.equal(await page.locator('#document-source').evaluate(input => input.scrollTop), 0);
    await page.evaluate(() => openFolderPath('/tmp/notes', true));
    await page.locator('[data-rail-action="find"]').click();
    assert.equal(await page.locator('#folder-search-input').isVisible(), true, 'folder search works without an open document');
    await page.evaluate(() => { const base = window.__TAURI__.core.invoke; window.__TAURI__.core.invoke = (command, args) => command === 'search_folder' ? Promise.resolve({ results: [{ name: 'match.md', path: '/tmp/notes/match.md', snippet: 'A content match' }] }) : base(command, args); });
    await page.locator('#folder-search-input').fill('match');
    await page.locator('#folder-search-results .grep-match').waitFor();
    assert.match(await page.locator('#folder-search-results').textContent(), /match.md/);
    assert.deepEqual(session.errors, []);
    await page.screenshot({ path: '/tmp/folio-application-menus.png' });
    console.log('PASS: application menus, Reading default, shared source history, permission guard, replace, preferences and document actions');
  } finally { await session.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
