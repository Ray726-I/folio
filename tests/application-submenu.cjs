const assert = require('node:assert/strict');
const { openEditor } = require('./editor-browser.cjs');

(async () => {
  const session = await openEditor('# Menu layout\n');
  const { page } = session;
  try {
    await page.evaluate(() => preferences.set('recent', ['/tmp/Notes.md', '/tmp/Project plan.md']));
    await page.locator('#menu-file-button').click();
    const parentBefore = await page.locator('#open-menu').boundingBox();
    await page.locator('#open-recent-button').click();
    const parent = await page.locator('#open-menu').boundingBox();
    const submenu = await page.locator('#open-recent-menu').boundingBox();
    assert.ok(submenu.x >= parent.x + parent.width - 1, 'recent files open to the right of File');
    assert.equal(parent.height, parentBefore.height, 'opening a submenu does not expand File');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#open-recent-menu').isVisible(), false);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'open-recent-button');
    assert.equal(await page.locator('#open-menu').isVisible(), true);
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#open-recent-menu button:first-child').evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('ArrowLeft');
    await page.locator('#open-file').hover();
    await page.locator('#open-recent-button').hover();
    await page.locator('#open-recent-menu').waitFor({ state: 'visible' });
    assert.equal(await page.evaluate(() => document.activeElement.id), 'open-recent-button', 'hover does not move keyboard focus');
    await page.locator('#open-recent-menu button:first-child').hover();
    assert.equal(await page.locator('#open-recent-menu').isVisible(), true, 'pointer can enter flyout');
    await page.locator('#open-file').hover();
    await page.locator('#open-recent-menu').waitFor({ state: 'hidden' });
    await page.setViewportSize({ width: 480, height: 420 });
    await page.locator('#open-recent-button').click();
    const narrow = await page.locator('#open-recent-menu').boundingBox();
    assert.ok(narrow.x >= 8 && narrow.x + narrow.width <= 472, 'flyout fits narrow windows');
    assert.ok(narrow.y >= 8 && narrow.y + narrow.height <= 412, 'flyout fits short windows');
    await page.locator('#open-recent-menu button:first-child').click();
    assert.equal(await page.locator('#open-menu').isVisible(), false);
    assert.equal(await page.locator('#open-recent-menu').isVisible(), false);
    await page.setViewportSize({ width: 1180, height: 500 });
    await page.evaluate(() => preferences.set('recent', Array.from({ length: 60 }, (_, i) => '/tmp/Document ' + i + '.md')));
    await page.locator('#menu-file-button').click();
    await page.locator('#open-recent-button').focus();
    await page.keyboard.press('ArrowRight');
    const long = await page.locator('#open-recent-menu').boundingBox();
    assert.ok(long.y >= 8 && long.y + long.height <= 492, 'long recent lists stay within the viewport');
    await page.keyboard.press('End');
    assert.equal(await page.locator('#open-recent-menu button:last-child').evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Home');
    assert.equal(await page.locator('#open-recent-menu button:first-child').evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Escape');
    await page.evaluate(() => preferences.set('recent', []));
    await page.keyboard.press('ArrowRight');
    assert.match(await page.locator('#open-recent-menu').textContent(), /No recent files/);
    await page.mouse.click(700, 450);
    assert.equal(await page.locator('#open-recent-menu').isVisible(), false, 'outside click closes both menus');
    assert.equal(await page.locator('#open-menu').isVisible(), false);
    assert.deepEqual(session.errors, []);
    console.log('PASS: application submenu placement, pointer, keyboard and viewport behavior');
  } finally { await session.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
