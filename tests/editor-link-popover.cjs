const assert = require('node:assert/strict');
const { buildEditorBundle, openIsolatedEditor } = require('./editor-temp-bundle.cjs');
(async () => {
  const bundle = buildEditorBundle();
  const source = 'A [guide](https://example.com/guide) and [section](#target).\n\nBody text.\n\n## Target\n\n<a href="https://example.org/html">HTML link</a>\n\n[<kbd>keys</kbd>](https://example.org/keys)\n\n[prefix <kbd>wrapped</kbd> tail](https://example.org/wrap)\n';
  const s = await openIsolatedEditor(source, bundle.outfile, { width: 1000, height: 720 });
  const { page } = s;
  // On macOS Control+click is the secondary-click gesture, so use Command for
  // the modifier-open path the editor implements for both platforms.
  const openModifier = process.platform === 'darwin' ? 'Meta' : 'Control';
  const popup = page.getByRole('dialog', { name: 'Link actions', exact: true });
  const link = () => page.getByRole('link', { name: 'guide', exact: true });
  const opened = () => page.evaluate(() => calls.filter(call => call.command === 'open_link').map(call => call.args.url));
  try {
    await page.evaluate(() => { window.copiedLink = ''; Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.copiedLink = text; } } }); });
    await link().click(); await popup.waitFor({ timeout: 3000 });
    assert.equal(await page.locator('#editor-action-dialog').isVisible(), false, 'clicking a link offers actions rather than immediately editing');
    assert.equal(await popup.locator('.folio-link-destination').textContent(), 'https://example.com/guide');
    assert.equal(await page.evaluate(() => current.content), source);
    await page.keyboard.press('ArrowRight');
    assert.equal(await popup.getByRole('button', { name: 'Edit link', exact: true }).evaluate(node => document.activeElement === node), true);
    await page.keyboard.press('ArrowRight');
    assert.equal(await popup.getByRole('button', { name: 'Copy link', exact: true }).evaluate(node => document.activeElement === node), true);
    await popup.getByRole('button', { name: 'Copy link', exact: true }).click();
    assert.equal(await page.evaluate(() => copiedLink), 'https://example.com/guide');
    assert.equal(await popup.count(), 0);
    await link().click(); await popup.waitFor({ timeout: 5000 });
    await page.keyboard.press('Enter');
    assert.deepEqual(await opened(), ['https://example.com/guide']);
    await link().click(); await popup.waitFor({ timeout: 5000 });
    await popup.getByRole('button', { name: 'Edit link', exact: true }).click();
    await page.locator('#editor-action-value').fill('https://example.com/changed');
    await page.locator('#editor-action-form button[type=submit]').click();
    await page.waitForFunction(() => current.content.includes('https://example.com/changed'));
    await page.keyboard.press('Control+z');
    await page.waitForFunction(value => current.content === value, source);
    await link().click({ modifiers: [openModifier] });
    await link().click({ button: 'middle' });
    assert.equal((await opened()).length, 3, 'modifier and middle clicks open directly');
    assert.equal(await popup.count(), 0);
    await page.evaluate(() => setDocumentMode('reading'));
    await link().click(); assert.equal((await opened()).length, 4, 'Read mode opens directly');
    await link().focus(); await page.keyboard.press('Enter');
    assert.equal((await opened()).length, 5, 'focused Read-mode links open with Enter');
    await page.evaluate(() => setDocumentMode('edit'));
    await link().click(); await popup.waitFor({ timeout: 5000 });
    await page.keyboard.press('Escape');
    assert.equal(await popup.count(), 0);
    assert.equal(await page.evaluate(() => document.activeElement.classList.contains('ProseMirror')), true);
    const drag = await link().boundingBox();
    await page.mouse.move(drag.x + 2, drag.y + drag.height / 2); await page.mouse.down();
    await page.mouse.move(drag.x + drag.width - 2, drag.y + drag.height / 2, { steps: 8 }); await page.mouse.up();
    await page.waitForTimeout(350);
    assert.equal(await popup.count(), 0, 'dragging link text must preserve selection without opening actions');
    assert.equal(await page.evaluate(() => document.activeElement.classList.contains('ProseMirror')), true);
    await link().dblclick(); await page.waitForTimeout(350);
    assert.equal(await popup.count(), 0, 'double click keeps text selection');
    await link().click();
    await page.locator('#word-count').click();
    await page.waitForTimeout(350);
    assert.equal(await popup.count(), 0, 'outside pointer down cancels a pending popover');
    await page.getByRole('link', { name: 'HTML link', exact: true }).click(); await popup.waitFor({ timeout: 5000 });
    await popup.getByRole('button', { name: 'Open link', exact: true }).click();
    assert.equal((await opened()).at(-1), 'https://example.org/html');
    await page.locator('.html-inline > a[href="https://example.org/keys"]').click({ modifiers: [openModifier] });
    assert.equal((await opened()).at(-1), 'https://example.org/keys');
    await page.locator('.html-inline > a[href="https://example.org/keys"]').click(); await popup.waitFor({ timeout: 5000 });
    await popup.getByRole('button', { name: 'Edit link', exact: true }).click();
    assert.equal(await page.locator('#editor-action-value').inputValue(), 'https://example.org/keys', 'Markdown links around inline HTML edit their destination');
    await page.locator('#editor-action-cancel').click();
    await page.locator('.html-inline > a[href="https://example.org/wrap"]').click(); await popup.waitFor({ timeout: 5000 });
    await popup.getByRole('button', { name: 'Edit link', exact: true }).click();
    assert.equal(await page.locator('#editor-action-value').inputValue(), 'https://example.org/wrap', 'inline HTML in the middle of a link edits the complete link destination');
    await page.locator('#editor-action-cancel').click();
    await page.getByRole('link', { name: 'section', exact: true }).click(); await popup.waitFor({ timeout: 5000 });
    await popup.getByRole('button', { name: 'Open link', exact: true }).click();
    assert.equal(await page.evaluate(() => editor.getSelection().head), source.indexOf('Target'));
    await page.setViewportSize({ width: 360, height: 560 });
    await link().click(); await popup.waitFor({ timeout: 5000 });
    const bounds = await popup.boundingBox();
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 360 && bounds.y >= 0 && bounds.y + bounds.height <= 560, 'popover fits a narrow viewport');
    await page.screenshot({ path: '/tmp/folio-link-popover.png' });
    await page.evaluate(() => editor.replaceContent(current.content + '\nChanged.\n'));
    assert.equal(await popup.count(), 0, 'document changes dismiss stale actions');
    assert.deepEqual(s.errors, []);
    console.log('PASS: link popover actions, direct shortcuts, Read mode, dismissal, undo and narrow layout');
  } finally { await s.close(); bundle.cleanup(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
