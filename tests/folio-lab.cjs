const assert = require('node:assert/strict');
const { openEditor } = require('./editor-browser.cjs');
(async () => {
  const session = await openEditor('# Test\n\nA paragraph for reading.\n\nAnother paragraph for reading.\n');
  const { page } = session;
  try {
    await page.locator('#document-more-button').click();
    await page.locator('#document-more-menu').getByRole('menuitem', { name: 'Folio Lab' }).click({ timeout: 3000 });
    assert.equal(await page.locator('#lab-dialog').evaluate(el => el.open), true);
    await page.keyboard.press('Escape');
    await page.keyboard.press('Control+Shift+p');
    await page.locator('#command-search').fill('Folio Lab');
    await page.locator('#command-dialog').getByText('Folio Lab', { exact: true }).click();
    await page.waitForFunction(() => document.getElementById('lab-dialog').open);
    await page.keyboard.press('Escape');
    await page.locator('#menu-view-button').click();
    await page.getByRole('menuitem', { name: 'Folio Lab' }).click();
    assert.equal(await page.getByRole('dialog', { name: 'Folio Lab' }).count(), 1);
    const search = page.getByRole('searchbox', { name: 'Search Folio Lab' });
    await search.fill('reading');
    assert.equal(await page.getByRole('heading', { name: 'Retro Terminal' }).isVisible(), false);
    assert.equal(await page.getByRole('heading', { name: 'Reading Guide' }).isVisible(), true);
    await search.fill('no matching extra');
    assert.equal(await page.getByText('No extras found').isVisible(), true);
    await search.fill('');
    await page.setViewportSize({ width: 420, height: 650 });
    assert.equal(await page.locator('#lab-dialog').evaluate(el => el.scrollWidth <= el.clientWidth), true, 'gallery fits a narrow window');
    assert.equal(await page.getByRole('button', { name: 'Use Retro Terminal' }).isVisible(), true);
    await page.setViewportSize({ width: 1180, height: 900 });
    if (process.env.LAB_SCREENSHOT) await page.screenshot({ path: process.env.LAB_SCREENSHOT });
    await page.getByRole('button', { name: 'Use Retro Terminal' }).click();
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'retro-terminal');
    assert.match(await page.locator('#preview').evaluate(el => getComputedStyle(el).fontFamily), /JetBrains Mono/);
    assert.match(await page.locator('#menu-view-button').evaluate(el => getComputedStyle(el).fontFamily), /JetBrains Mono/);
    await page.getByRole('button', { name: 'Enable Reading Guide' }).click();
    assert.equal(await page.locator('body').evaluate(el => el.classList.contains('lab-reading-guide')), true);
    await page.keyboard.press('Escape');
    await page.evaluate(() => setDocumentMode('reading'));
    if (process.env.LAB_THEME_SCREENSHOT) await page.screenshot({ path: process.env.LAB_THEME_SCREENSHOT });
    const guide = page.getByRole('toolbar', { name: 'Reading Guide' });
    await guide.waitFor({ state: 'visible', timeout: 3000 });
    await page.waitForFunction(() => document.getElementById('reading-guide-position').textContent.includes('1 of 2'));
    await page.getByRole('button', { name: 'Next paragraph' }).click();
    await page.waitForFunction(() => document.getElementById('reading-guide-position').textContent.includes('2 of 2'));
    assert.equal(await page.getByRole('button', { name: 'Next paragraph' }).isDisabled(), true);
    await page.getByRole('button', { name: 'Previous paragraph' }).click();
    await page.waitForFunction(() => document.getElementById('reading-guide-position').textContent.includes('1 of 2'));
    assert.equal(await page.locator('#reading-guide-marker').isVisible(), true);
    await page.locator('#reader-scroll').focus();
    await page.keyboard.press('ArrowDown');
    await page.waitForFunction(() => document.getElementById('reading-guide-position').textContent.includes('2 of 2'), null, { timeout: 3000 });
    await page.keyboard.press('ArrowUp');
    await page.waitForFunction(() => document.getElementById('reading-guide-position').textContent.includes('1 of 2'), null, { timeout: 3000 });
    await page.evaluate(() => setDocumentMode('edit'));
    assert.equal(await guide.isVisible(), false);
    await page.evaluate(() => setDocumentMode('reading'));
    await page.reload();
    await page.waitForFunction(() => document.body.classList.contains('lab-reading-guide'));
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'retro-terminal');
    await page.locator('#menu-view-button').click();
    await page.getByRole('menuitem', { name: 'Folio Lab' }).click();
    await page.getByRole('button', { name: 'Disable Reading Guide' }).click();
    assert.equal(await page.locator('body').evaluate(el => el.classList.contains('lab-reading-guide')), false);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#lab-dialog').evaluate(el => el.open), false);
    await page.evaluate(() => applyTheme('paper'));
    assert.doesNotMatch(await page.locator('#menu-view-button').evaluate(el => getComputedStyle(el).fontFamily), /JetBrains Mono/, 'switching themes restores normal interface typography');
  } finally { await session.close(); }
  const longSession = await openEditor('# Long document\n\n' + Array.from({ length: 45 }, (_, i) => `Paragraph ${i + 1} with enough text to read.`).join('\n\n'));
  try {
    const page = longSession.page;
    await page.evaluate(() => { setLabExtension('reading-guide', true); setDocumentMode('reading'); });
    await page.waitForFunction(() => document.getElementById('reading-guide-position').textContent.includes('of 45'));
    await page.locator('#reader-scroll').evaluate(el => { el.scrollTop = el.scrollHeight; });
    await page.waitForFunction(() => parseInt(document.getElementById('reading-guide-position').textContent, 10) > 20);
    assert.equal(await page.locator('#reading-guide-marker').isVisible(), true);
  } finally { await longSession.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
