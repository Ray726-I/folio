const assert=require('node:assert/strict');
const {openEditor}=require('./editor-browser.cjs');
(async()=>{
 const s=await openEditor('# Shortcuts\n\n```js\nconst n = 1;\n```\n');
 try {const {page}=s;
  const fence=page.locator('.code-fence-info');await fence.focus();
  await page.keyboard.press('Control+Shift+p');
  assert.equal(await page.locator('#command-dialog').isVisible(),true,'palette opens while code language input owns focus');
  const zoomBefore=await page.evaluate(()=>windowZoom);
  await page.keyboard.press('Control+=');
  assert.equal(await page.evaluate(()=>windowZoom),zoomBefore+.1,'window zoom works while palette is open');
  await page.keyboard.press('Control+-');
  assert.equal(await page.evaluate(()=>windowZoom),zoomBefore,'window zoom reverses');
  const textBefore=await page.evaluate(()=>fontSize);
  await page.keyboard.press('Control+Shift+=');
  assert.ok(await page.evaluate(()=>fontSize)>textBefore,'text zoom works while palette is open');
  await page.keyboard.press('Control+Shift+-');
  assert.equal(await page.evaluate(()=>fontSize),textBefore,'text zoom reverses');
  await page.keyboard.press('Control+Shift+p');assert.equal(await page.locator('#command-dialog').isVisible(),false,'shortcut toggles palette closed');
  await fence.focus();const before=await page.evaluate(()=>windowZoom);await page.keyboard.press('Control+=');assert.equal(await page.evaluate(()=>windowZoom),before+.1,'input cannot swallow window zoom');
  await page.evaluate(()=>showHelp(true));await page.keyboard.press('Control+Shift+p');assert.equal(await page.locator('#command-dialog').isVisible(),true,'palette opens above help');
  await page.keyboard.press('Escape');assert.equal(await page.locator('#help-dialog').isVisible(),true,'closing palette restores the underlying dialog');
  await page.evaluate(()=>$('help-dialog').close());
  await page.evaluate(()=>{window.shortcutPrompt=ask('Confirm test','Choose an option',[{label:'Cancel',value:'cancel'},{label:'Continue',value:'continue'}]);});
  await page.locator('#confirm-dialog').waitFor({state:'visible'});
  await page.keyboard.press('Control+Shift+p');assert.equal(await page.locator('#command-dialog').isVisible(),true,'palette opens above confirmation');
  await page.keyboard.press('Control+Shift+p');assert.equal(await page.locator('#confirm-dialog').isVisible(),true,'confirmation stays open');
  await page.evaluate(()=>{window.queuedPrompt=ask('Queued prompt','Waits for the open confirmation',[{label:'Dismiss',value:'dismiss'}]);});
  await page.waitForTimeout(50);
  assert.equal(await page.locator('#confirm-title').textContent(),'Confirm test','a second prompt does not replace the open confirmation');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();assert.equal(await page.evaluate(()=>window.shortcutPrompt),'cancel');
  await page.locator('#confirm-dialog').waitFor({state:'visible'});
  assert.equal(await page.locator('#confirm-title').textContent(),'Queued prompt','the queued prompt opens after the first settles');
  await page.getByRole('button',{name:'Dismiss',exact:true}).click();assert.equal(await page.evaluate(()=>window.queuedPrompt),'dismiss');
  const beforeAlt=await page.evaluate(()=>windowZoom);
  await page.keyboard.press('Control+Alt+=');assert.equal(await page.evaluate(()=>windowZoom),beforeAlt,'AltGr combinations do not trigger zoom');
  assert.deepEqual(s.errors,[]);console.log('PASS: palette and zoom shortcuts work in nested inputs and dialogs');
 }finally{await s.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
