const assert = require('node:assert/strict');
const { openEditor } = require('./editor-browser.cjs');
(async () => {
 const s = await openEditor('# First\n\nSelectable text in the main document.\n\n```js\nconst value = 1;\n```\n', {width:1440,height:900});
 try {
  const {page}=s;
  await page.evaluate(()=>{current.documentId='primary';registerDocument(current);showReadingCompanion();});
  await page.waitForSelector('#companion-preview h1');
  assert.equal(await page.locator('#pane-divider').evaluate(el=>getComputedStyle(el).borderLeftStyle),'solid','split divider is visible');
  const b=await page.locator('#pane-divider').boundingBox();
  await page.mouse.move(b.x+b.width/2,b.y+80);await page.mouse.down();await page.mouse.move(b.x+100,b.y+110,{steps:12});
  assert.equal(await page.evaluate(()=>getSelection().toString()),'','resizing must not select companion text');
  await page.mouse.up();
  await page.evaluate(()=>{setDocumentMode('reading');showReadingCompanion({documentId:'side',name:'Side.md',content:'# Side\n\nSIDE_PANE_SENTINEL',saved:'# Side\n\nSIDE_PANE_SENTINEL',active:true},false);});
  await page.waitForFunction(()=>$('companion-preview').textContent.includes('SIDE_PANE_SENTINEL'));
  const mainText=await page.locator('#preview p').first().boundingBox(), sideText=await page.locator('#companion-preview p').boundingBox();
  await page.mouse.move(mainText.x+5,mainText.y+mainText.height/2);await page.mouse.down();await page.mouse.move(sideText.x+sideText.width/2,sideText.y+sideText.height/2,{steps:15});await page.mouse.up();
  assert.ok(!(await page.evaluate(()=>getSelection().toString())).includes('SIDE_PANE_SENTINEL'),'dragging right never selects the other reading pane');
  await page.evaluate(()=>{getSelection().removeAllRanges();setDocumentMode('edit');});
  assert.equal(await page.evaluate(()=>document.documentElement.classList.contains('pane-resizing')),false);
  await page.evaluate(()=>{closeReadingCompanion();for(let i=0;i<14;i++)registerDocument({documentId:'extra-'+i,name:`Long document number ${i}.md`,path:`/folder/${i}.md`,content:'',saved:'',active:true});renderTabs();});
  assert.ok(await page.locator('#tab-list .tab-item').first().evaluate(el=>el.getBoundingClientRect().width)<180,'tabs shrink before overflowing');
  assert.equal(await page.locator('#tab-scroll-next').isVisible(),true);
  const original=await page.evaluate(()=>current.documentId);
  await page.keyboard.press('Control+Tab');await page.waitForFunction(id=>current.documentId!==id&&!busy,original);
  const forward=await page.evaluate(()=>current.documentId);assert.notEqual(forward,original);
  await page.keyboard.press('Control+Shift+Tab');await page.waitForFunction(id=>current.documentId===id&&!busy,original);
  await page.keyboard.press('Control+Shift+Tab');await page.waitForFunction(()=>current.documentId==='extra-13'&&!busy);
  await page.keyboard.press('Control+Tab');await page.waitForFunction(id=>current.documentId===id&&!busy,original);
  await page.locator('#tab-extra-13').click({button:'middle'});await page.waitForFunction(()=>!documents.has('extra-13')&&!busy);
  const dragged=await page.locator('.document-tab').first().boundingBox(), pane=await page.locator('.pane-layout').boundingBox();
  await page.mouse.move(dragged.x+20,dragged.y+dragged.height/2);await page.mouse.down();await page.mouse.move(pane.x+pane.width*.8,pane.y+100,{steps:15});
  await page.waitForFunction(() => document.querySelector('.pane-layout').classList.contains('pane-drop-target'));
  const drop = await page.evaluate(() => { const el=document.querySelector('.pane-layout'), style=getComputedStyle(el,'::after'); return {left:parseFloat(style.left), width:el.clientWidth, content:style.content}; });
  assert.equal(drop.content, '""'); assert.ok(Math.abs(drop.left-drop.width/2)<1, 'drop highlight begins at the right half');
  await page.mouse.up();
  await page.waitForFunction(()=>companionDocument===current);assert.equal(await page.locator('#reading-companion').isVisible(),true,'tab drop opens a companion');
  await page.evaluate(()=>closeReadingCompanion());
  await page.locator('.document-tab').first().focus();await page.keyboard.press('Shift+F10');
  assert.equal(await page.locator('#tab-context-menu').isVisible(),true,'tab menu opens from keyboard');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#tab-context-menu').isVisible(),false);
  assert.equal(await page.locator('#document-location').isVisible(),false,'path does not occupy the header');
  await page.keyboard.press('Control+3');assert.equal(await page.evaluate(()=>documentMode),'source');
  await page.keyboard.press('Control+2');assert.equal(await page.evaluate(()=>documentMode),'edit');
  await page.locator('#document-mode-menu-button').click();
  assert.equal(await page.locator('button[data-document-mode="edit"]').getAttribute('aria-checked'),'true');
  await page.keyboard.press('Escape');
  await page.evaluate(()=>{openFind();$('find-input').value='selectable';updateFind();});
  assert.equal(await page.locator('#find-result').textContent(),'1 / 1');
  await page.locator('#find-case').click();assert.equal(await page.locator('#find-result').textContent(),'No matches');
  await page.locator('#find-case').click();
  await page.locator('#find-regex').click();await page.locator('#find-input').fill('[');
  assert.match(await page.locator('#find-result').textContent(),/Invalid/);
  await page.evaluate(()=>{closeFind();showHelp(true);});
  assert.ok(await page.locator('#help-content h3').count()>=3,'shortcuts are grouped');
  assert.deepEqual(s.errors,[]);
  console.log('PASS: interaction polish, tab overflow, accessible menus and divider drag');
 } finally {await s.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
